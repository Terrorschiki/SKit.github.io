# -*- coding: utf-8 -*-
"""Publish the built site to the repository root.

GitHub Pages for `Terrorschiki/SKit.github.io` serves the site at
https://terrorschiki.github.io/SKit.github.io/ , so the published files must sit
at the repository root — the `/SKit.github.io/` path in the URL comes from the
repository name, not from a folder.

`site/` is the staging tree produced by build_catalog.py / build_pages.py;
this script mirrors its publishing subset to the repository root and removes
anything it no longer contains, so a rebuild is always reproducible.
"""
import io, json, os, shutil, sys

sys.stdout.reconfigure(encoding="utf-8")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)          # repository root == published site root
SITE = os.path.join(ROOT, "site")     # staging tree

# Directories published verbatim from site/ into the repository root.
# (_build/ is tooling, site/ is staging, .git/ is the repository itself.)
# data/ holds catalog.json and the i18n dictionaries the front-end fetches.
PUBLISH_DIRS = ("assets", "data", "collections", "products", "downloads")

# Individual files published at the repository root.
PUBLISH_FILES = (
    "index.html", "collections.html", "about.html", "contact.html",
    "downloads.html", "404.html", "sitemap.xml", "robots.txt", "README.md",
)

# Files generated by this script rather than copied.
GENERATED = (".nojekyll",)

SKIP_NAMES = {".DS_Store", "Thumbs.db", "__pycache__"}

# Top-level entries that must survive a prune.
KEEP_TOP = set(PUBLISH_DIRS) | set(PUBLISH_FILES) | set(GENERATED) | {
    ".git", ".gitignore", ".github", "_build", "site",
}


def copy_tree(src, dst):
    for root, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in SKIP_NAMES]
        rel = os.path.relpath(root, src)
        target = dst if rel == "." else os.path.join(dst, rel)
        os.makedirs(target, exist_ok=True)
        for f in files:
            if f in SKIP_NAMES:
                continue
            shutil.copy2(os.path.join(root, f), os.path.join(target, f))


def prune_published_root():
    """Remove stale published output from the repository root.

    Only stale *published* output is considered: the original supplier
    workbooks (source data for the whole build) and the tooling directories are
    never touched, whatever their names.
    """
    removed = []
    for name in os.listdir(ROOT):
        if name in KEEP_TOP or name.endswith((".xlsx", ".pdf")):
            continue
        path = os.path.join(ROOT, name)
        if os.path.isdir(path):
            shutil.rmtree(path)
        else:
            os.remove(path)
        removed.append(name)
    return removed


def ensure_workflow():
    """GitHub only reads workflows from <repo-root>/.github/workflows/."""
    wf = os.path.join(ROOT, ".github", "workflows", "pages.yml")
    if os.path.exists(wf):
        return "present"
    alt = os.path.join(SITE, ".github", "workflows", "pages.yml")
    if os.path.exists(alt):
        os.makedirs(os.path.dirname(wf), exist_ok=True)
        shutil.copy2(alt, wf)
        return "restored from site/"
    return None


def main():
    if not os.path.isdir(SITE):
        sys.exit("site/ not found — run build_catalog.py and build_pages.py first")

    cat = json.load(io.open(os.path.join(SITE, "data", "catalog.json"), encoding="utf-8"))

    # 1. drop stale top-level entries the build no longer produces
    removed = prune_published_root()
    if removed:
        print("removed stale top-level entries:", ", ".join(sorted(removed)))

    # 2. mirror the publishing subset to the repository root
    for d in PUBLISH_DIRS:
        src = os.path.join(SITE, d)
        if not os.path.isdir(src):
            print(f"  ! missing {d}/ in site/ — skipped")
            continue
        copy_tree(src, os.path.join(ROOT, d))
    for f in PUBLISH_FILES:
        src = os.path.join(SITE, f)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(ROOT, f))
        else:
            print(f"  ! missing {f} in site/ — skipped")

    # 3. GitHub Pages: skip Jekyll entirely
    with io.open(os.path.join(ROOT, ".nojekyll"), "w") as fh:
        fh.write("")
    print("workflow (.github/workflows/pages.yml):", ensure_workflow() or "MISSING")

    # 4. prune product images no catalogue entry references any more
    img_dir = os.path.join(ROOT, "assets", "products")
    expected = set()
    for p in cat["products"]:
        for tag in ("thumb", "card", "full"):
            expected.add(f"{p['id']}-{tag}.jpg")
    for k in ("l", "p", "s"):
        expected.add(f"{k}-hero.jpg")
    pruned = 0
    for f in os.listdir(img_dir):
        if f.endswith(".jpg") and f not in expected:
            os.remove(os.path.join(img_dir, f))
            pruned += 1
    if pruned:
        print(f"pruned {pruned} orphaned product image(s)")

    # 5. verify published coverage
    missing_img = []
    for p in cat["products"]:
        for tag in ("thumb", "card", "full"):
            if not os.path.exists(os.path.join(img_dir, f"{p['id']}-{tag}.jpg")):
                missing_img.append(f"{p['id']}-{tag}")
    missing_pages = [p["id"] for p in cat["products"]
                     if not os.path.exists(os.path.join(ROOT, "products", p["id"] + ".html"))]

    files = size = 0
    for r, ds, fs in os.walk(ROOT):
        parts = r.split(os.sep)
        if ".git" in parts or "_build" in parts or "site" in parts:
            continue
        for f in fs:
            files += 1
            size += os.path.getsize(os.path.join(r, f))

    print(f"\npublished: {files} files, {size/1048576:.1f} MB")
    print(f"products: {len(cat['products'])}  "
          f"missing images: {len(missing_img)}  missing pages: {len(missing_pages)}")
    if missing_img:
        print("  first missing image:", missing_img[:6])
    if missing_pages:
        print("  first missing page :", missing_pages[:6])
    for k in ("L", "P", "S"):
        print(f"  set {k}: {sum(1 for p in cat['products'] if p['set']==k)} items")


if __name__ == "__main__":
    main()
